def load_server_environment(project: Path, environment: dict[str, str]) -> dict[str, str]:
    """Load local server secrets, creating an ignored development file once.

    The API deliberately refuses empty credentials.  A first ``run`` must still
    be usable, so this function creates distinct high-entropy local values in
    ``.env`` when it does not exist.  The file is ignored by Git and values
    already supplied by the operating-system environment take precedence.
    """
    env_file = project / ".env"
    if not env_file.is_file():
        ingest = secrets.token_urlsafe(32)
        control = secrets.token_urlsafe(32)
        operator = secrets.token_urlsafe(32)
        camera_config_key = secrets.token_urlsafe(48)
        studio_password = secrets.token_urlsafe(24)
        env_file.write_text(
            "# Local development secrets. Generated by armor-project; do not commit.\n"
            "ARMOR_PORT=8080\n"
            f"ARMOR_INGEST_TOKEN={ingest}\n"
            f"ARMOR_CONTROL_TOKEN={control}\n"
            f"ARMOR_OPERATOR_TOKEN={operator}\n"
            f"ARMOR_CAMERA_CONFIG_KEY={camera_config_key}\n"
            "ARMOR_STUDIO_ORIGIN=http://127.0.0.1:5178\n"
            "ARMOR_STUDIO_USERNAME=admin\n"
            f"ARMOR_STUDIO_PASSWORD={studio_password}\n",
            encoding="utf-8",
        )
        report("ARMOR_LOCAL_SECRETS=CREATED .env (Git-ignored)")
    for line in env_file.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        # An inherited empty variable must not shadow the valid local value.
        # This happens easily after a failed manual command in cmd.exe.
        current = environment.get(key.strip(), "")
        if key and (not current or current.startswith("replace-with-")):
            environment[key.strip()] = value.strip()
    return environment


PANEL: "Panel | None" = None   # the live panel of the run (see pretty_run.py); None prints the plain lines of before


def report(line: str) -> None:
    """A status line of the workflow: a skipped step is a line of the panel, anything else a dimmed note."""
    if PANEL is None:
        print(line)
        return
    name, _, rest = line.partition(" ")
    if "SKIPPED" in line or "NOT_BUILT" in line:
        PANEL.skip(name.split("=")[0].replace("_", " ").capitalize(), rest)
    else:
        PANEL.note(line)


def step_title(args: list[str]) -> str:
    """A short name for a step, from its command: `npm run typecheck`, `python -m pytest`."""
    words = [Path(args[0]).stem if Path(args[0]).suffix.lower() in (".exe", ".bat", ".cmd") else Path(args[0]).name] + [a for a in args[1:] if not a.startswith("-") or a == "-m"]
    return " ".join(words)[:52]


def command(project: Path, args: list[str], environment: dict[str, str] | None = None) -> None:
    if PANEL is not None:
        if not PANEL.step(step_title(args), args, cwd=project, env=environment, tests=True):
            raise RuntimeError("a step failed (its output is above)")
        return
    print("$", " ".join(args), flush=True)
    try:
        result = subprocess.run(args, cwd=project, env=environment, check=False)
    except FileNotFoundError as error:
        raise RuntimeError(f"required executable was not found: {args[0]}") from error
    if result.returncode:
        raise RuntimeError(f"command failed with exit code {result.returncode}")


def check_tool(name: str, message: str) -> str:
    path = shutil.which(name)
    if not path:
        raise RuntimeError(message)
    return path


def project_python(project: Path) -> str:
    """The Python of the checkout's own virtual environment with pytest in it (made the first time)."""
    folder = project / ".venv"
    python = folder / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
    if not python.is_file():
        command(project, [sys.executable, "-m", "venv", str(folder)])
    probe = subprocess.run([str(python), "-c", "import pytest"], capture_output=True)
    if probe.returncode != 0:
        command(project, [str(python), "-m", "pip", "install", "-q", "pytest>=8.0"])
    return str(python)


NODE_REPOSITORIES = ("ARMOR-NODE-ALARM", "ARMOR-NODE-ELECTRICAL", "ARMOR-NODE-HMI", "ARMOR-NODE-RADAR", "ARMOR-NODE-SOLAR")


def siblings_required() -> bool:
    """In CI (ARMOR_REQUIRE_SIBLINGS=1) a check that needs the other repositories next to this one fails when they are missing; on a machine it says it was skipped."""
    return os.environ.get("ARMOR_REQUIRE_SIBLINGS", "") not in ("", "0")


def test_common(project: Path) -> None:
    """ARMOR-COMMON: its unit tests, then what it generates (the types and the conformance vectors must be the ones its sources produce) and that the firmware the five nodes share is identical to the base."""
    environment = os.environ.copy()
    environment["PYTHONPATH"] = str(project / "src") + os.pathsep + environment.get("PYTHONPATH", "")
    command(project, [sys.executable, "-m", "unittest", "discover", "-s", "tests"], environment)
    command(project, [sys.executable, "tools/generate_types.py", "--check"], environment)
    command(project, [sys.executable, "tools/make_conformance.py", "--check"], environment)
    present = [node for node in NODE_REPOSITORIES if (project.parent / node).is_dir()]
    if len(present) == len(NODE_REPOSITORIES):
        command(project, [sys.executable, "tools/sync_firmware_base.py", "check", "--root", str(project.parent)], environment)
    elif siblings_required():
        raise RuntimeError("the node repositories are not next to ARMOR-COMMON, so the shared firmware could not be compared (missing: " + ", ".join(sorted(set(NODE_REPOSITORIES) - set(present))) + ")")
    else:
        report("FIRMWARE_BASE=SKIPPED the node repositories are not next to ARMOR-COMMON")


def host_tests(project: Path, build: Path) -> None:
    """Run every test program the project's CMake registers (a list written by hand here left some of them out, among them the ones that check the signature of a firmware)."""
    ctest = check_tool("ctest", "CTest (it comes with CMake) is required to run the host tests")
    command(project, [ctest, "--test-dir", str(build), "--output-on-failure"])


def unit_tests(project: Path, folder: str = "tests") -> None:
    """The standard-library unit tests of a repository that is not a Python program (documentation, hardware): every tests/test_*.py. A repository without the folder says so and goes on."""
    if not (project / folder).is_dir():
        report(f"UNIT_TESTS=SKIPPED there is no {folder}/ folder")
        return
    command(project, [sys.executable, "-m", "unittest", "discover", "-s", folder, "-p", "test_*.py"])


# The shell tests that need Docker, and the two that only repeat what the Python discovery already runs.
DEVOPS_SHELL_TESTS_LEFT_OUT = {"test_compose.sh", "test_admin_agent.sh", "test_maintenance_agent.sh"}


def devops_tests(project: Path) -> None:
    """ARMOR-DEVOPS: the Python tests of its helpers (the admin agent, the maintenance agent, the packager) and every shell test of its scripts, all offline and in temporary folders.
    They need Unix sockets, bash and openssl (Linux, macOS, WSL); on Windows they are reported as not run, never as passed."""
    scripts = project / "scripts"
    if os.name == "nt":
        report("DEVOPS_TESTS=SKIPPED they need Unix sockets, bash and openssl: run build-test on Linux, macOS or WSL")
        return
    command(project, [sys.executable, "-W", "ignore", "-m", "unittest", "discover", "-s", "scripts", "-p", "test_*.py"])
    bash = check_tool("bash", "bash is required to run the shell tests of ARMOR-DEVOPS")
    for script in sorted(scripts.glob("test_*.sh")):
        if script.name not in DEVOPS_SHELL_TESTS_LEFT_OUT:
            command(project, [bash, str(script)])


def test_project(project: Path, manifest: dict[str, object]) -> None:
    name = str(manifest["name"])
    if name == "ARMOR-COMMON":
        test_common(project)
    elif name in PYTHON_PROJECTS:
        environment = os.environ.copy()
        environment["PYTHONPATH"] = str(project / "src") + os.pathsep + environment.get("PYTHONPATH", "")
        command(project, [sys.executable, "-m", "unittest", "discover", "-s", "tests"], environment)
    elif name in PYTEST_PROJECTS:
        # A stdlib-only CLI/install core with a pytest-based test suite. The tests run from `src` (PYTHONPATH) with pytest from a virtual environment of this checkout (`.venv`,
        # ignored by git): the project itself is never installed. It used to be `pip install -e`, which pointed the installation at the folder of the build - for the updater that is a
        # staging folder that is renamed a moment later, so the updated updater could not be imported - and put it in the system Python, which Debian and Raspberry Pi OS refuse (PEP 668).
        python = project_python(project)
        environment = os.environ.copy()
        environment["PYTHONPATH"] = str(project / "src") + os.pathsep + environment.get("PYTHONPATH", "")
        command(project, [python, "-m", "pytest", "tests", "-q"], environment)
    elif name in NODE_PROJECTS:
        check_tool("npm", "npm is required; install Node.js 22 or newer")
        # A fresh checkout (every CI run; a developer machine only the first
        # time) has no node_modules yet - found for real when ARMOR-SERVER's
        # and ARMOR-STUDIO's own CI runs failed with "Cannot find module"
        # for every import, because typecheck ran before anything installed
        # a single dependency. Reusing an existing tree (rather than
        # reinstalling unconditionally) matters on a developer machine,
        # where a running editor/linter can hold a native module's file
        # open.
        if not (project / "node_modules").is_dir():
            command(project, [NPM, "ci"])
        command(project, [NPM, "run", "typecheck"])
        command(project, [NPM, "test"])
        command(project, [NPM, "run", "build"])
    elif name == "ARMOR-NODE-RADAR":
        test_radar(project)
    elif name == "ARMOR-NODE-SOLAR":
        test_solar(project)
    elif name == "ARMOR-NODE-ELECTRICAL":
        test_electrical(project)
    elif name == "ARMOR-NODE-ALARM":
        test_alarm(project)
    elif name == "ARMOR-NODE-HMI":
        test_hmi(project)
    elif name == "ARMOR-ANDROID-CONTROL":
        gradle = "gradlew.bat" if os.name == "nt" and (project / "gradlew.bat").is_file() else ("./gradlew" if (project / "gradlew").is_file() else check_tool("gradle", "Gradle or the project wrapper is required; open the project in Android Studio once to generate/restore it"))
        command(project, [gradle, "test", "assembleDebug"])
    elif name == "ARMOR-IOS-CONTROL":
        # no Mac needed: the structure, the eight language tables and the contract are checked in Python, and the tests of ArmorCore run wherever a Swift toolchain exists (macOS, Linux)
        command(project, [sys.executable, "tools/ios_lint.py"])
        swift = shutil.which("swift")
        if swift:
            command(project, [swift, "test"])
        elif os.environ.get("ARMOR_REQUIRE_SWIFT"):
            raise RuntimeError("Swift is required to run the tests of ArmorCore")
        else:
            report("SWIFT_TESTS=SKIPPED no Swift toolchain on this machine (they run in CI)")
    elif name == "ARMOR-HARDWARE":
        unit_tests(project)
        openscad = check_tool("openscad", "OpenSCAD is required to validate the parametric enclosure")
        output = project / "build" / "node_enclosure_radar.stl"
        output.parent.mkdir(exist_ok=True)
        command(project, [openscad, "-o", str(output), "scad/node_enclosure_radar.scad"])
        # Every piece is rendered on its own, so an assert of the source (a board that does not fit, a cable hole in a wall) or a part that is not a solid fails here and not on the printer.
        for view_mode, piece in ((2, "base"), (3, "cover")):
            command(project, [openscad, "-D", f"view_mode={view_mode}", "-o", str(project / "build" / f"node_enclosure_radar_{piece}.stl"), "scad/node_enclosure_radar.scad"])
        for preset in ("solar", "electrical", "alarm"):
            for part in ("box", "lid"):
                command(project, [openscad, "-D", f'part="{part}"', "-D", f'preset="{preset}"', "-o", str(project / "build" / f"node_box_{preset}_{part}.stl"), "scad/node_box.scad"])
    elif name == "ARMOR-DEVOPS":
        devops_tests(project)
        check_tool("docker", "Docker Compose is required to validate ARMOR-DEVOPS")
        # `docker compose config` only checks the topology is well formed; it
        # still needs every variable the compose file interpolates to have
        # SOME value. generate_secrets.sh's own real, disposable secrets are
        # exactly that - CI never reuses them past this one validation run.
        if not (project / ".env").is_file():
            command(project, ["bash", "scripts/generate_secrets.sh"])
        command(project, ["docker", "compose", "config", "--quiet"])
    elif name == "ARMOR-DOCS":
        validate_markdown_links(project)
        unit_tests(project)
    else:
        raise RuntimeError(f"no build rule registered for {name}")


def check_broker(project: Path, samples: str = "") -> None:
    """The messages a node's serialiser prints, through a real Mosquitto with a stand-in for the node's MQTT client (tests/check_mosquitto.py). Where Mosquitto is not installed the check says so and
    passes; the CI of the node repositories installs it and sets ARMOR_REQUIRE_MOSQUITTO, so there a missing broker is a failure."""
    checker = subprocess.run([sys.executable, "tests/check_mosquitto.py"], cwd=project, input=samples, text=True, check=False)
    if checker.returncode:
        raise RuntimeError("a real MQTT broker and the node's client do not agree (tests/check_mosquitto.py)")


def test_radar(project: Path) -> None:
    """Build and run the hardware-independent core on this computer, then the firmware if ESP-IDF is present.

    The host tests need CMake and a C++17 compiler (Linux, macOS, WSL or MSYS2). The firmware image itself
    needs ESP-IDF; without it the run says so instead of pretending the image was built.
    """
    cmake = check_tool("cmake", "CMake and a C++17 compiler are required to test ARMOR-NODE-RADAR's core (use Linux, WSL or MSYS2)")
    build = project / "build" / "host"
    command(project, [cmake, "-S", "tests", "-B", str(build), "-DCMAKE_BUILD_TYPE=Debug"])
    command(project, [cmake, "--build", str(build)])
    suffix = ".exe" if os.name == "nt" else ""
    host_tests(project, build)
    emitter = subprocess.run([str(build / f"emit_samples{suffix}")], cwd=project, capture_output=True, text=True, check=True)
    checker = subprocess.run([sys.executable, "tests/check_contract.py"], cwd=project, input=emitter.stdout, text=True, check=False)
    if checker.returncode:
        raise RuntimeError("the firmware serialiser produces payloads the published contract rejects")
    check_broker(project, emitter.stdout)
    if shutil.which("idf.py"):
        command(project, ["idf.py", "build"])
    else:
        report("ARMOR_RADAR_FIRMWARE=NOT_BUILT ESP-IDF (idf.py) was not found; only the host-tested core was verified")


