def validate_markdown_links(project: Path) -> None:
    missing: list[str] = []
    link = re.compile(r"\[[^]]+\]\(([^)]+)\)")
    for file in project.rglob("*.md"):
        for target in link.findall(file.read_text(encoding="utf-8")):
            target = target.split("#", 1)[0]
            if not target or "://" in target or target.startswith("mailto:"):
                continue
            if not (file.parent / target).resolve().is_file():
                missing.append(f"{file.relative_to(project)} -> {target}")
    if missing:
        raise RuntimeError("broken local Markdown links:\n" + "\n".join(missing))
    report("ARMOR_DOCS_LINKS=PASS")


def next_version(version: str) -> str:
    """The odometer of the family: no component ever reaches 10 (0.2.9 -> 0.3.0). Three components up to 0.7.9; from 0.8.0 a project has four (0.7.9 -> 0.8.0.0 -> 0.8.0.9 -> 0.8.1.0 -> ... -> 0.8.9.9 -> 0.9.0.0)."""
    numbers = [int(part) for part in version.split(".")]
    if len(numbers) == 3 and numbers[:2] >= [0, 8]:
        return ".".join(str(number) for number in numbers + [0])   # 0.8.0 is already 0.8.0.0
    if numbers == [0, 7, 9]:
        return "0.8.0.0"
    index = len(numbers) - 1
    numbers[index] += 1
    while index > 0 and numbers[index] == 10:
        numbers[index] = 0
        index -= 1
        numbers[index] += 1
    return ".".join(str(number) for number in numbers)


def bump(project: Path, manifest: dict[str, object]) -> tuple[str, str]:
    before = str(manifest["version"])
    parts = before.split(".")
    if len(parts) not in (3, 4) or any(not part.isdigit() for part in parts):
        raise RuntimeError("manifest version must use major.minor.patch (or major.minor.patch.build) numeric format")
    after = next_version(before)
    manifest["version"] = after
    manifest["native_version"] = after
    manifest_path = project / "armor.project.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    # Android considers versionCode/versionName part of the install/update
    # identity.  Leaving Gradle at the old values after the shared manifest
    # bump creates an APK which Android quite correctly refuses as stale.
    # Keep this narrow to ARMOR's native client rather than guessing layouts
    # for every project that happens to contain a Gradle file.
    if manifest.get("name") == "ARMOR-ANDROID-CONTROL":
        gradle_file = project / "app" / "build.gradle.kts"
        if not gradle_file.is_file():
            raise RuntimeError("ARMOR-ANDROID-CONTROL is missing app/build.gradle.kts")
        gradle = gradle_file.read_text(encoding="utf-8")
        code_match = re.search(r"versionCode\s*=\s*(\d+)", gradle)
        name_match = re.search(r'versionName\s*=\s*"[^"]+"', gradle)
        if not code_match or not name_match:
            raise RuntimeError("ARMOR-ANDROID-CONTROL Gradle version fields are missing")
        gradle = gradle[:code_match.start(1)] + str(int(code_match.group(1)) + 1) + gradle[code_match.end(1):]
        gradle = re.sub(r'versionName\s*=\s*"[^"]+"', f'versionName = "{after}"', gradle, count=1)
        gradle_file.write_text(gradle, encoding="utf-8")
    # A Python project's own pyproject.toml `version` (PyPI-style packaging
    # identity) and its package `__init__.py`'s `__version__` mirror are a
    # separate copy of the number from armor.project.json's - found in
    # practice: ARMOR-NETWORK's pyproject.toml stayed at 0.0.1
    # while its manifest reached 0.0.2, and ARMOR-COMMON's stayed at 0.2.3
    # against a manifest already at 0.2.6, unnoticed because nothing kept
    # them in sync. Kept narrow to the projects that actually have a
    # pyproject.toml (every PYTHON_PROJECTS/PYTEST_PROJECTS member).
    if manifest.get("name") in PYTHON_PROJECTS | PYTEST_PROJECTS:
        pyproject_file = project / "pyproject.toml"
        if pyproject_file.is_file():
            pyproject = pyproject_file.read_text(encoding="utf-8")
            pyproject, count = re.subn(r'(?m)^version\s*=\s*"[^"]+"', f'version = "{after}"', pyproject, count=1)
            if count:
                pyproject_file.write_text(pyproject, encoding="utf-8")
        for init_file in (project / "src").glob("*/__init__.py"):
            init_text = init_file.read_text(encoding="utf-8")
            init_text, count = re.subn(r'(?m)^__version__\s*=\s*"[^"]+"', f'__version__ = "{after}"', init_text, count=1)
            if count:
                init_file.write_text(init_text, encoding="utf-8")
    changelog = project / "CHANGELOG.md"
    previous = changelog.read_text(encoding="utf-8") if changelog.is_file() else "# Changelog\n\nAll notable changes to this project are documented here.\n"
    entry = f"\n## [{after}] - {date.today().isoformat()}\n\n- Verified build completed; release version advanced from `{before}` to `{after}`.\n"
    marker = "\n## "
    at = previous.find(marker)
    content = previous + entry if at < 0 else previous[:at] + entry + previous[at:]
    changelog.write_text(content.rstrip() + "\n", encoding="utf-8")
    return before, after


def run_project(project: Path, manifest: dict[str, object]) -> None:
    name = str(manifest["name"])
    environment = os.environ.copy()
    if name in PYTHON_PROJECTS:
        environment["PYTHONPATH"] = str(project / "src") + os.pathsep + environment.get("PYTHONPATH", "")
        module = {"ARMOR-SIMULATOR": "armor_simulator", "ARMOR-NETWORK": "armor_network", "ARMOR-SERVER-AI": "armor_server_ai.cli", "ARMOR-VOICE-AI": "armor_voice_ai.gateway", "ARMOR-VISION": "armor_vision"}.get(name)
        if not module:
            print("ARMOR-COMMON is a library; run its tests or consume it from another project.")
            return
        command(project, [sys.executable, "-m", module], environment)
    elif name == "ARMOR-STUDIO":
        check_tool("npm", "npm is required; install Node.js 22 or newer")
        # Keep Vite alive after this launcher returns.  On Windows, prefer an
        # installed Chromium browser's fullscreen mode; a web page itself is
        # not allowed to enter fullscreen without a user gesture.
        if os.name == "nt":
            flags = getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0) | getattr(subprocess, "CREATE_NO_WINDOW", 0)
            subprocess.Popen(["cmd.exe", "/d", "/c", NPM, "run", "dev"], cwd=project, creationflags=flags)
        else:
            subprocess.Popen([NPM, "run", "dev"], cwd=project)
        time.sleep(2)
        url = "http://127.0.0.1:5178"
        if os.name == "nt":
            browser = next((candidate for candidate in ("msedge.exe", "chrome.exe") if shutil.which(candidate)), None)
            if browser:
                subprocess.Popen([browser, "--start-fullscreen", url], creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
            else:
                webbrowser.open_new(url)
        else:
            webbrowser.open_new(url)
        print(f"ARMOR_STUDIO=LAUNCHED url={url} fullscreen_requested=True")
    elif name in NODE_PROJECTS:
        if name == "ARMOR-SERVER":
            environment = load_server_environment(project, environment)
        command(project, [NPM, "run", "dev"], environment)
    elif name == "ARMOR-DEVOPS":
        command(project, ["docker", "compose", "up", "--build"])
    elif name in {"ARMOR-NODE-RADAR", "ARMOR-NODE-SOLAR", "ARMOR-NODE-ELECTRICAL", "ARMOR-NODE-ALARM", "ARMOR-NODE-HMI", "ARMOR-ANDROID-CONTROL", "ARMOR-IOS-CONTROL", "ARMOR-HARDWARE", "ARMOR-DOCS", "ARMOR-UPDATER"}:
        print(f"{name} has no safe generic runtime command. Use build-test to validate it, then follow its project documentation for hardware or IDE deployment.")
    else:
        raise RuntimeError(f"no run rule registered for {name}")


def main() -> int:
    parser = argparse.ArgumentParser(description="A.R.M.O.R. standardized project workflow")
    parser.add_argument("action", choices=("build", "build-test", "test", "run"))
    parser.add_argument("project", type=Path)
    args = parser.parse_args()
    project = args.project.resolve()
    manifest_path = project / "armor.project.json"
    if not manifest_path.is_file():
        raise RuntimeError(f"manifest not found: {manifest_path}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("ecosystem") != "A.R.M.O.R.":
        raise RuntimeError("refusing non-A.R.M.O.R. manifest")
    global PANEL
    PANEL = None   # a run that comes after another one in the same process starts clean
    # the panel is for a person at a terminal (or when ARMOR_PRETTY=1 asks for it); a log, a pipe or a test gets the plain lines
    wanted = os.environ.get("ARMOR_PRETTY") == "1" or (os.environ.get("ARMOR_PRETTY") != "0" and sys.stdout.isatty())
    if Panel is not None and wanted and args.action != "run":
        PANEL = Panel(str(manifest["name"]), args.action, str(manifest["version"]), "A.R.M.O.R.")
        PANEL.banner()
    else:
        print(f"PROJECT={manifest['name']} VERSION={manifest['version']} ACTION={args.action}")
    if args.action == "run":
        run_project(project, manifest)
        return 0
    try:
        test_project(project, manifest)
    except RuntimeError as error:
        if PANEL is None:
            raise
        if not any(step[1] == "fail" for step in PANEL.steps):   # a step that failed has already said so above
            PANEL.fail("Workflow", str(error))
        return PANEL.finish()
    if args.action == "build":
        before, after = bump(project, manifest)
        # The version change above must be compiled into the Android APK; a
        # second, incremental Gradle pass is what makes build.bat produce an
        # installable artifact whose version equals its manifest.
        if manifest.get("name") == "ARMOR-ANDROID-CONTROL":
            test_project(project, manifest)
        done = f"VERSION_BUMP=PASS v{before} -> v{after}"
    else:
        done = "BUILD_TEST=PASS manifest and CHANGELOG unchanged"
    if PANEL is None:
        print(done)
        return 0
    return PANEL.finish(done)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (RuntimeError, json.JSONDecodeError) as error:
        print(f"ARMOR_WORKFLOW=FAIL {error}", file=sys.stderr)
        raise SystemExit(1) from error
